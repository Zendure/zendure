"""Generate ``src/zendure/catalog/_fault_tables.py`` from the fault-table export.

Input is ``fault_export_en.json``: a read-only export of the cloud's
``t_device_fault`` table (English rows only), refreshed by hand when the table
changes. The library never talks to that database at runtime.

A row applies to a model when its ``product_type`` list contains the model's
type id and its ``product_model`` list contains the model id, or is NULL (all
models of the type). This mirrors the cloud backend. An empty-string
``product_model`` matches nothing there, and nothing here.

When several rows define the same code for one model, the most specific wins:
a row naming models beats a NULL one, fewer named models beat more, and the
lowest id breaks a tie. The backend picks one arbitrarily (``limit 1`` without
an order); this rule makes the 5000 Max Pro's own definitions win over the
SolarFlow-wide ones they conflict with.

Usage::

    python scripts/gen_faults.py            # rewrite the module
    python scripts/gen_faults.py --check    # exit 1 if it is out of date
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Final, NamedTuple

ROOT: Final = Path(__file__).resolve().parents[1]
EXPORT: Final = Path(__file__).with_name("fault_export_en.json")
TARGET: Final = ROOT / "src" / "zendure" / "catalog" / "_fault_tables.py"

# model_key -> (product_type id, product_model id) in the cloud database.
MODELS: Final = {
    "solarflow_2400ac_plus": ("29", "65"),
    "solarflow_5000_max_pro": ("22", "86"),
}


class Row(NamedTuple):
    id: int
    code: int
    name: str | None
    module: str | None
    fault_level: int | None
    type: int | None
    product_type: str | None
    product_model: str | None


def _ids(value: str | None) -> list[str]:
    return [part.strip() for part in (value or "").split(",") if part.strip()]


def applies(row: Row, type_id: str, model_id: str) -> bool:
    """Whether ``row`` defines a fault for the given type/model."""
    if type_id not in _ids(row.product_type):
        return False
    if row.product_model is None:
        return True
    return model_id in _ids(row.product_model)


def _specificity(row: Row) -> tuple[int, int, int]:
    if row.product_model is None:
        return (1, 0, row.id)
    return (0, len(_ids(row.product_model)), row.id)


def resolve(rows: list[Row], type_id: str, model_id: str) -> dict[int, Row]:
    """Pick one row per code for a model, most specific first."""
    best: dict[int, Row] = {}
    for row in rows:
        if not applies(row, type_id, model_id):
            continue
        current = best.get(row.code)
        if current is None or _specificity(row) < _specificity(current):
            best[row.code] = row
    return dict(sorted(best.items()))


def load(path: Path = EXPORT) -> list[Row]:
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return [Row(*values) for values in data["rows"]]


def _literal(value: object) -> str:
    # json.dumps gives a valid Python literal for str/int and escapes quotes.
    return "None" if value is None else json.dumps(value, ensure_ascii=False)


def render(rows: list[Row]) -> str:
    lines = [
        '"""Generated by scripts/gen_faults.py from fault_export_en.json. Do not edit.',
        "",
        "Rows: (code, name, module, fault_level, display_type). ``fault_level`` and",
        "``display_type`` keep the cloud table's raw values; ``faults.py`` interprets",
        "them.",
        '"""',
        "",
        "from typing import Final",
        "",
        "type FaultRow = tuple[int, str | None, str | None, int | None, int | None]",
        "",
        "# fmt: off",
        "FAULT_ROWS: Final[dict[str, tuple[FaultRow, ...]]] = {",
    ]
    for model_key, (type_id, model_id) in MODELS.items():
        lines.append(f'    "{model_key}": (')
        for row in resolve(rows, type_id, model_id).values():
            module = row.module.strip().upper() if row.module else None
            name = row.name.strip() if row.name else None
            fields = ", ".join(
                _literal(v) for v in (row.code, name, module, row.fault_level, row.type)
            )
            lines.append(f"        ({fields}),")
        lines.append("    ),")
    lines += ["}", "# fmt: on", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only verify")
    args = parser.parse_args()
    content = render(load())
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print(f"{TARGET.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
